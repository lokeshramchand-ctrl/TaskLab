  flame: ['regular', 'flame'],
  trend: ['regular', 'trend-up'],
  headphones: ['regular', 'headphones'],
  clock: ['regular', 'clock'],
  sliders: ['regular', 'sliders-horizontal'],
  calendar: ['regular', 'calendar-blank'],
  star: ['regular', 'star'],
  disc: ['regular', 'disc'],
  mic: ['regular', 'microphone'],
  zap: ['regular', 'lightning'],
