"""Builds src/components/linear-icons.ts from the SVGs exported from the Linear Design System (Figma community file).
Run: python scripts/gen-linear-icons.py
Monochrome icons are repainted with currentColor; the status icons keep their own colours (they carry meaning)."""
import json, os, re

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, 'linear-icons')
out = os.path.join(here, '..', 'src', 'components', 'linear-icons.ts')
STATUS = {'st-progress', 'st-done', 'st-backlog', 'st-todo', 'st-canceled'}

icons = {}
for f in sorted(os.listdir(src)):
    if not f.endswith('.svg'):
        continue
    name = f[:-4]
    s = open(os.path.join(src, f), encoding='utf8').read()
    size = int(re.search(r'viewBox="0 0 (\d+) ', s).group(1))
    body = re.sub(r'<svg[^>]*>', '', s).replace('</svg>', '')
    body = re.sub(r'<defs>.*?</defs>', '', body, flags=re.S)
    body = re.sub(r'<g clip-path="[^"]*">', '', body).replace('</g>', '')
    body = re.sub(r' clip-path="[^"]*"', '', body)
    body = re.sub(r'\s*\n\s*', '', body).strip()
    if name not in STATUS:
        body = re.sub(r'(fill|stroke)="#[0-9A-Fa-f]{3,8}"', r'\1="currentColor"', body)
    icons[name] = {'s': size, 'b': body}

with open(out, 'w', encoding='utf8') as w:
    w.write('// Generated by scripts/gen-linear-icons.py from the Linear Design System (Figma community file). Do not edit by hand.\n')
    w.write('// s = artboard size in px, b = SVG body. Mono icons use currentColor, status icons keep their own colours.\n')
    w.write('export const LINEAR: Record<string, { s: number; b: string }> = ')
    w.write(json.dumps(icons, indent=1))
    w.write(';\n\nexport type LinearName = keyof typeof LINEAR;\n')
print(len(icons), 'icons ->', os.path.relpath(out))
