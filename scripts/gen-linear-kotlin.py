"""Builds app/.../ui/LinearIcons.kt from the SVGs in web/scripts/linear-icons (the Linear Design System icons the web player uses).
Run: python scripts/gen-linear-kotlin.py   (mono icons only; the coloured status icons are skipped)."""
import os, re

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'web', 'scripts', 'linear-icons')
out = os.path.join(here, '..', 'app', 'src', 'main', 'kotlin', 'com', 'lomu', 'app', 'ui', 'LinearIcons.kt')

def ident(n):
    return ''.join(p.capitalize() for p in n.split('-'))

entries = []
for f in sorted(os.listdir(src)):
    if not f.endswith('.svg') or f.startswith('st-'):
        continue
    name = f[:-4]
    s = open(os.path.join(src, f), encoding='utf8').read()
    size = int(re.search(r'viewBox="0 0 (\d+) ', s).group(1))
    body = re.sub(r'<defs>.*?</defs>', '', s, flags=re.S)
    paths = []
    for m in re.finditer(r'<path ([^>]*?)/>', body):
        a = m.group(1)
        d = re.search(r' ?d="([^"]+)"', a).group(1)
        paths.append((d, 'fill-rule="evenodd"' in a))
    if not paths:
        print('skip (no paths):', name); continue
    entries.append((ident(name), size, paths))

with open(out, 'w', encoding='utf8') as w:
    w.write('// Generated by scripts/gen-linear-kotlin.py from the Linear Design System icons used by the web player. Do not edit by hand.\n')
    w.write('package com.lomu.app.ui\n\n')
    w.write('import androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.graphics.PathFillType\nimport androidx.compose.ui.graphics.SolidColor\n')
    w.write('import androidx.compose.ui.graphics.vector.ImageVector\nimport androidx.compose.ui.graphics.vector.PathParser\nimport androidx.compose.ui.unit.dp\n\n')
    w.write('/** Linear icons (same set as the web player). Each path is filled; the tint is applied by the caller. */\n')
    w.write('enum class Lin(private val size: Float, private val paths: List<Pair<String, Boolean>>) {\n')
    for i, (n, size, paths) in enumerate(entries):
        ps = ', '.join('"%s" to %s' % (d, 'true' if eo else 'false') for d, eo in paths)
        w.write('    %s(%sf, listOf(%s))%s\n' % (n, size, ps, ',' if i < len(entries) - 1 else ';'))
    w.write('''
    val vector: ImageVector by lazy {
        ImageVector.Builder(name = name, defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = size, viewportHeight = size).apply {
            paths.forEach { (d, evenOdd) ->
                addPath(PathParser().parsePathString(d).toNodes(), fill = SolidColor(Color.Black), pathFillType = if (evenOdd) PathFillType.EvenOdd else PathFillType.NonZero)
            }
        }.build()
    }
}
''')
print(len(entries), 'icons ->', os.path.relpath(out))
